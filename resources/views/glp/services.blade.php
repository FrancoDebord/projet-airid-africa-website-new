<div class="glp-tile">
    <h3>GLP Testing Services</h3>
    <p>AIRID provides GLP-compliant evaluation of vector control products across laboratory bioassays, experimental hut
        trials, and field studies, in accordance with OECD Good Laboratory Practice (GLP) and World Health Organization
        Prequalification (WHO/PQ) vector control evaluation guidelines.</p>

    <h4>Vector Control Products Tested</h4>
    <p>AIRID conducts GLP studies on a broad range of vector control products, including:</p>
    <ul>
        <li>Insecticide-treated nets (ITNs), including next-generation and dual-active nets</li>
        <li>Indoor residual spraying (IRS) products</li>
        <li>Spatial repellents and emanators</li>
        <li>Larvicides and larval source management tools</li>
        <li>Novel and emerging vector control technologies</li>
    </ul>
    <p class="mb-0">Products may be evaluated at different stages of development, including pre-submission testing, WHO
        prequalification support, and post-market evidence generation.</p>

    <h4>Testing Platforms</h4>
    <p>Depending on the regulatory question and product class, evaluations may be conducted using one or more of the
        following GLP-aligned platforms:</p>
    <p><strong>Laboratory Bioassays</strong></p>
    <ul>
        <li>WHO-recommended laboratory assays</li>
        <li>Assessment of bioefficacy, susceptibility, and relevant entomological endpoints</li>
        <li>Conducted under GLP where applicable</li>
    </ul>
    <p><strong>Semi-Field and Experimental Hut Trials</strong></p>
    <ul>
        <li>Controlled evaluation of product performance under realistic exposure conditions</li>
        <li>Measurement of WHO-recommended entomological endpoints</li>
        <li>Studies aligned with regulatory and policy requirements</li>
    </ul>
    <p><strong>Field Trials</strong></p>
    <ul>
        <li>GLP-aligned field evaluations, where appropriate</li>
        <li>Assessment of durability, operational performance, and real-world effectiveness</li>
    </ul>
    <p class="mb-0">All studies are designed and conducted in line with applicable WHO/PQ Vector Control Product
        Evaluation Guidelines.</p>
    <p class="mt-2 mb-0"><a
