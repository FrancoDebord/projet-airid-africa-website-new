    </div>
    <div class="col-lg-6 order-1 order-lg-2">
        <div class="fac-flight-tile h-100">
    <p>The Mosquito Release Chambers are used for:</p>
    <ul>
        <li>Evaluation of indoor vector control products, including insecticide-treated nets, indoor residual spraying (IRS) and novel tools</li>
        <li>Flight room experiments for spatial emanators</li>
        <li>Behavioural assessment of mosquito entry, host-seeking, feeding, and exiting responses</li>
        <li>Comparative testing using insectary-reared mosquitoes with defined susceptibility or resistance profiles</li>
        <li>Supporting progression from laboratory bioassays to semi-field and experimental hut studies</li>
    </ul>
    <p>These applications generate high-quality entomological data to inform intervention selection and optimisation.</p>
