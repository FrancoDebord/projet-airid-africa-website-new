    <div class="strategy-block">
        <h3 class="strategy-block-title">
            <i class="fas fa-flask"></i> Pillar 1: Strengthen Scientific Research and Innovation
        </h3>
        <p class="section-content mb-2">
            <strong>Strategic goal:</strong> Build world-class research programmes addressing malaria and other infectious diseases through rigorous science, innovative technologies, and partnership-driven research.
        </p>
        <p class="section-content mb-2"><strong>Objectives (2024–2028):</strong></p>
        <ul class="strategy-list">
            <li>Establish robust research programmes in:
                <ul class="strategy-list">
                    <li>Vector control and public health entomology</li>
                    <li>Disease surveillance, diagnostics and molecular epidemiology</li>
                    <li>Health policy, systems and economics</li>
                    <li>Community health, social science and community acceptance</li>
                    <li>Data science, analytics and modelling</li>
                </ul>
            </li>
            <li>Conduct high-quality evaluations of next-generation vector control products (ITNs, IRS, spatial repellents, GMMs, larvicides).</li>
            <li>Develop an experimental platform for testing genetically modified mosquitoes and novel tools.</li>
            <li>Publish at least 25 peer-reviewed scientific papers by 2028.</li>
            <li>Expand AIRID’s research portfolio to include three new disease areas beyond malaria.</li>
        </ul>
    </div>

    <div class="strategy-divider"></div>

    <div class="strategy-row">
        <div class="strategy-col">
            <div class="strategy-block">
                <h3 class="strategy-block-title">
                    <i class="fas fa-microscope"></i> Pillar 2: Build State-of-the-Art Research Infrastructure
                </h3>
                <p class="section-content mb-2">
                    <strong>Strategic goal:</strong> Develop modern laboratory and field infrastructures to support cutting-edge research in entomology, molecular biology, and analytical chemistry.
                </p>
                <p class="section-content mb-2"><strong>Objectives (2024–2028):</strong></p>
                <ul class="strategy-list">
                    <li>Establish a fully functional Analytical Chemistry Laboratory capable of quantifying insecticide content and treated materials.</li>
                    <li>Expand the Molecular Biology &amp; Genomics Laboratory for species identification, resistance markers, sequencing, and pathogen detection.</li>
                    <li>Modernize insectaries and experimental hut sites to meet international standards.</li>
                    <li>Develop a data center for secure data storage and analysis.</li>
                    <li>Strengthen health, safety, and quality systems with full SOPs and biosafety compliance.</li>
                </ul>
            </div>
        </div>
        <div class="strategy-col">
            <div class="strategy-block">
                <h3 class="strategy-block-title">
                    <i class="fas fa-users"></i> Pillar 3: Strengthen Human Capacity and Scientific Leadership
                </h3>
                <p class="section-content mb-2">
                    <strong>Strategic goal:</strong> Train and support the next generation of African scientists and research leaders.
                </p>
                <p class="section-content mb-2"><strong>Objectives (2024–2028):</strong></p>
                <ul class="strategy-list">
                    <li>Recruit and train scientists, technicians, field staff, and administrative personnel.</li>
                    <li>Establish a training academy providing short courses in entomology, GLP, molecular biology, analytical chemistry, quality assurance, and epidemiology.</li>
                    <li>Supervise Master’s and PhD students in collaboration with LSTM, LSHTM, CREC, PAMVERC-BENIN, University of Abomey-Calavi, and regional institutions.</li>
                    <li>Create professional development pathways, including mentorship, leadership training, and conference participation.</li>
                    <li>Secure fellowships and training grants to support early-career researchers.</li>
                </ul>
            </div>
        </div>
    </div>

    <div class="strategy-row">
        <div class="strategy-col">
            <div class="strategy-block">
                <h3 class="strategy-block-title">
                    <i class="fas fa-handshake"></i> Pillar 4: Strengthen Partnerships, Policy Engagement &amp; Regional Leadership
                </h3>
                <p class="section-content mb-2">
                    <strong>Strategic goal:</strong> Position AIRID as a regional hub for vector control, implementation research, and policy engagement in West Africa.
                </p>
                <p class="section-content mb-2"><strong>Objectives (2024–2028):</strong></p>
                <ul class="strategy-list">
                    <li>Strengthen collaborations with NMCP Benin, CREC, universities, regional research institutions, WHO, RBM VCWG, and industry partners.</li>
                    <li>Participate actively in global networks (VCWG, PAMCA).</li>
                    <li>Lead or co-lead multi-country research consortia by 2027.</li>
                    <li>Produce evidence that informs national malaria control policy and WHO policy dialogues.</li>
                    <li>Host annual scientific symposia and training workshops in Benin.</li>
                </ul>
            </div>
        </div>
        <div class="strategy-col">
            <div class="strategy-block">
                <h3 class="strategy-block-title">
                    <i class="fas fa-university"></i> Pillar 5: Institutional Strengthening, Governance &amp; Sustainability
                </h3>
                <p class="section-content mb-2">
                    <strong>Strategic goal:</strong> Build a resilient, well-governed, and financially sustainable institution.
                </p>
                <p class="section-content mb-2"><strong>Objectives (2024–2028):</strong></p>
                <ul class="strategy-list">
                    <li>Develop and implement institutional policies in research integrity, ethics, safeguarding, finance, procurement, HR, quality systems, biosafety, risk management, and data protection.</li>
                    <li>Strengthen governance through the AIRID Board and Scientific Advisory Committee.</li>
                    <li>Establish efficient financial management systems aligned with donor regulations.</li>
                    <li>Diversify funding sources through grants, consultancy services, laboratory services, trainings, and partnerships.</li>
                    <li>Develop a long-term institutional sustainability plan.</li>
                </ul>
            </div>
        </div>
    </div>

