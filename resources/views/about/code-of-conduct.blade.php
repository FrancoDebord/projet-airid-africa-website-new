    <div class="code-block mb-4">
        <h3 class="code-block-title"><i class="fas fa-book-open"></i> Document contents</h3>
        <p class="section-content mb-3">
            The manual (Code MG-MN-1-003/01) covers: introduction (vision, mission, values), principles governing the code, individual responsibilities, zero-tolerance policy (sexual exploitation and abuse, harassment, discrimination, etc.), use of social media and communications, reporting obligations, disciplinary measures for violations, and staff acknowledgment and agreement. It aligns with AIRID’s protection policy, research ethics guidelines and dignity at work policy, and with international standards (IASC, human rights).
        </p>
    </div>

    <div class="code-block code-block-summary mb-4">
        <h3 class="code-block-title"><i class="fas fa-list-ul"></i> Summary</h3>
        <p class="section-content mb-0">
            The code applies to all staff, trainees, consultants and anyone representing AIRID, in all workplaces and when representing the Institute. Everyone commits to upholding AIRID’s integrity and reputation, promoting a safe and inclusive environment, complying with protection and dignity at work policies, conducting ethical research and reporting any misconduct or breach. AIRID enforces zero tolerance for sexual exploitation and abuse, harassment, discrimination and substance abuse. Violations result in disciplinary action.
        </p>
